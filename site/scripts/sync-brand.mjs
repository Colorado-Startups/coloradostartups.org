// Generates src/styles/tokens.css from 01_doctrine/brand_tokens.yaml.
// Runs on predev and prebuild. The tokens file is committed so a reader can see
// it, but it is never edited by hand: test/unit/brand-tokens-sync.test.ts
// regenerates it in memory and fails on any difference.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = resolve(here, "../../01_doctrine/brand_tokens.yaml");
export const TARGET = resolve(here, "../src/styles/tokens.css");

export function renderTokens(yamlText) {
  const doc = parse(yamlText);
  const lines = [
    "/* Generated by site/scripts/sync-brand.mjs from 01_doctrine/brand_tokens.yaml. Do not edit. */",
    ":root {",
    "  color-scheme: light;",
  ];
  for (const [group, prefix] of [
    ["color", "c"],
    ["space", "s"],
    ["radius", "r"],
    ["line", "line"],
    ["size", "size"],
    ["shadow", "sh"],
    ["type", "t"],
  ]) {
    for (const [name, value] of Object.entries(doc[group] ?? {})) {
      lines.push(`  --${prefix}-${name}: ${value};`);
    }
  }
  // Old color names point at their new roles, so earlier code keeps rendering.
  for (const [oldName, newName] of Object.entries(doc.alias ?? {})) {
    if (!(newName in (doc.color ?? {}))) throw new Error(`alias ${oldName} points at unknown color ${newName}`);
    lines.push(`  --c-${oldName}: var(--c-${newName});`);
  }
  lines.push("}");
  return lines.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, renderTokens(readFileSync(SOURCE, "utf8")));
  console.log("tokens.css written from brand_tokens.yaml");
}
