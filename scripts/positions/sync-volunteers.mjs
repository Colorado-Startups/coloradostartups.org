#!/usr/bin/env node
// Copies the volunteer kit's data into data/positions/ for the four seat pages
// (lane L38). Run it by hand, never in prebuild: Workers Builds builds from
// git, so the site can never read a folder on this Mac.
//
//   node scripts/positions/sync-volunteers.mjs [--from <dir>] [--check]
//
// --from   the kit's Roles folder. Defaults to $CS_VOLUNTEERS_DIR, then to
//          DEFAULT_KIT below, the kit's folder on the maintainer's machine.
// --check  writes nothing, and exits 1 when data/positions/ differs from the kit.
//
// It reads only roles.json, data/facts.json and data/geo.json, and writes:
//   data/positions/<seat id>.yaml  one role entry from roles.json
//   data/positions/common.yaml     what every seat shares
//   data/positions/facts.yaml      the facts a page may show: mark R, not gated, notes dropped
//   data/positions/geo.yaml        the map's coordinates
// Keys that start with "_" are the kit's own notes and never leave it.
//
// Exit codes follow the repo's checker contract: 0 clean, 1 drift or bad
// data, 2 usage error, 3 could not read the kit.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { toYaml } from "../canvas/lib/yaml.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUT_DIR = path.join(REPO, "data", "positions");
export const DEFAULT_KIT = path.join(homedir(), "Developer", "Colorado Startups", "Volunteers", "Roles");
const MARK = "Generated by scripts/positions/sync-volunteers.mjs";

/** The fields a page may show, in the order facts.yaml lists them. `note` is internal and never copied. */
export const FACT_FIELDS = ["value", "label", "source", "url", "read", "short", "bar"];
const FACT_REQUIRED = ["value", "label", "source", "url", "read", "short"];
const ROLE_REQUIRED = ["id", "title", "kind", "eyebrow", "where", "one_liner", "do", "bring", "rules_extra", "extra_courses"];
const COMMON_KEYS = ["org", "apply", "courses", "core_courses", "perks", "steps", "look_for", "rules_common", "linkedin_rule"];

export class KitError extends Error {
  /** @param {string} message @param {1 | 3} code 1 for bad data, 3 for a kit the script could not read */
  constructor(message, code) {
    super(message);
    this.code = code;
  }
}

/** A copy of a kit object without its "_" notes, keeping key order. */
function withoutNotes(value) {
  if (Array.isArray(value)) return value.map(withoutNotes);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => !key.startsWith("_"))
        .map(([key, v]) => [key, withoutNotes(v)]),
    );
  }
  return value;
}

/** True for a fact a page may show: read in full (mark R) and not held back (status gated). */
export function isPublicFact(fact) {
  return fact?.mark === "R" && fact?.status !== "gated";
}

/**
 * The facts a page may show, in the kit's order, each cut to FACT_FIELDS. An
 * S-marked fact (search snippet only) or a gated one drops out, and so does
 * every `note`. A kept fact missing a required field is bad data, not a fact
 * to drop quietly.
 */
export function publicFacts(facts) {
  const out = {};
  for (const [id, fact] of Object.entries(facts ?? {})) {
    if (!isPublicFact(fact)) continue;
    const missing = FACT_REQUIRED.filter((key) => typeof fact[key] !== "string" || fact[key] === "");
    if (missing.length > 0) throw new KitError(`facts.json: ${id} lacks ${missing.join(", ")}`, 1);
    out[id] = Object.fromEntries(FACT_FIELDS.filter((key) => fact[key] !== undefined).map((key) => [key, fact[key]]));
  }
  return out;
}

/** One seat's entry, as roles.json gives it. */
export function seatEntry(role) {
  const missing = ROLE_REQUIRED.filter((key) => role?.[key] === undefined);
  if (missing.length > 0) throw new KitError(`roles.json: role ${role?.id ?? "?"} lacks ${missing.join(", ")}`, 1);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(role.id)) throw new KitError(`roles.json: role id "${role.id}" is not a slug`, 1);
  return withoutNotes(role);
}

// roles.json records when the course pages were read only in its _about line.
// The seat pages cite that date for the course lengths, so the date is read
// from there, and a reworded line stops the sync rather than losing the date.
const COURSES_READ = /Course facts: academy\.claude\.com course pages, read (\d{4}-\d{2}-\d{2})/;

/** What every seat shares, plus the date the course lengths were read. */
export function commonEntry(roles) {
  const missing = COMMON_KEYS.filter((key) => roles?.[key] === undefined);
  if (missing.length > 0) throw new KitError(`roles.json lacks ${missing.join(", ")}`, 1);
  const read = COURSES_READ.exec(roles._about ?? "");
  if (!read) throw new KitError('roles.json _about no longer says "Course facts: academy.claude.com course pages, read <date>"', 1);
  return { ...Object.fromEntries(COMMON_KEYS.map((key) => [key, withoutNotes(roles[key])])), course_lengths_read: read[1] };
}

const pick = (obj, keys) => Object.fromEntries(keys.filter((k) => obj[k] !== undefined).map((k) => [k, obj[k]]));

/**
 * The map's coordinates: state bounds, cities, peaks and any landmarks. The
 * Census cross-checks and the provenance notes stay in the kit, which the
 * header's hash names; a map that carries no figures needs neither.
 */
export function geoEntry(geo) {
  if (!geo?.state_bounds || !Array.isArray(geo.cities)) throw new KitError("geo.json lacks state_bounds or cities", 1);
  return {
    state_bounds: pick(geo.state_bounds, ["north", "south", "west", "east"]),
    cities: geo.cities.map((c) => pick(c, ["name", "lat", "lon", "region", "core", "gnis_id"])),
    peaks: (geo.peaks ?? []).map((p) => pick(p, ["name", "lat", "lon", "gnis_id"])),
    landmarks: (geo.landmarks ?? []).map((l) => pick(l, ["name", "lat", "lon", "region"])),
  };
}

const sha = (text) => createHash("sha256").update(text).digest("hex").slice(0, 16);

function header(what, file, hash) {
  return [`${MARK} from the volunteer kit's ${file}`, `(sha256 ${hash}). ${what}`, "Do not edit by hand: change the kit, then run the script again."];
}

/** Every file the kit produces, as { "<name>.yaml": text }. Pure, so tests can call it without a kit on disk. */
export function render(kit) {
  const roles = kit.roles;
  if (!Array.isArray(roles?.roles) || roles.roles.length === 0) throw new KitError("roles.json lists no roles", 1);
  const files = {};
  for (const role of roles.roles) {
    const entry = seatEntry(role);
    files[`${entry.id}.yaml`] = toYaml(entry, header(`The ${entry.title} seat.`, "roles.json", kit.hashes.roles));
  }
  files["common.yaml"] = toYaml(commonEntry(roles), header("What every seat shares.", "roles.json", kit.hashes.roles));
  files["facts.yaml"] = toYaml(
    publicFacts(kit.facts?.facts),
    header("Only facts marked R and not gated, without notes.", "data/facts.json", kit.hashes.facts),
  );
  files["geo.yaml"] = toYaml(geoEntry(kit.geo), header("Map coordinates.", "data/geo.json", kit.hashes.geo));
  return files;
}

/** Reads the three kit files. Throws KitError(code 3) when the folder or a file is missing or does not parse. */
export function readKit(dir) {
  if (!existsSync(dir)) throw new KitError(`the volunteer kit is not at ${dir}; pass --from <dir>`, 3);
  const read = (rel) => {
    const file = path.join(dir, rel);
    let text;
    try {
      text = readFileSync(file, "utf8");
    } catch (err) {
      throw new KitError(`cannot read ${rel} in the kit (${err.code ?? err.message})`, 3);
    }
    try {
      return { json: JSON.parse(text), hash: sha(text) };
    } catch (err) {
      throw new KitError(`${rel} in the kit is not JSON (${err.message})`, 3);
    }
  };
  const roles = read("roles.json");
  const facts = read("data/facts.json");
  const geo = read("data/geo.json");
  return {
    roles: roles.json,
    facts: facts.json,
    geo: geo.json,
    hashes: { roles: roles.hash, facts: facts.hash, geo: geo.hash },
  };
}

/** Files in outDir this script wrote before, by name. Hand-written files are never touched. */
function generatedFiles(outDir) {
  if (!existsSync(outDir)) return [];
  return readdirSync(outDir).filter((name) => name.endsWith(".yaml") && readFileSync(path.join(outDir, name), "utf8").includes(MARK));
}

/** Runs the sync and returns the exit code. */
export function main(argv = process.argv.slice(2), { outDir = OUT_DIR, log = console.log, warn = console.error } = {}) {
  let from = process.env.CS_VOLUNTEERS_DIR || DEFAULT_KIT;
  let check = false;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--check") check = true;
    else if (argv[i] === "--from" && argv[i + 1]) from = argv[(i += 1)];
    else {
      warn(`usage: sync-volunteers.mjs [--from <dir>] [--check] (unknown argument "${argv[i]}")`);
      return 2;
    }
  }
  let files;
  try {
    files = render(readKit(from));
  } catch (err) {
    if (err instanceof KitError) {
      warn(`sync-volunteers: ${err.message}`);
      return err.code;
    }
    throw err;
  }
  const stale = generatedFiles(outDir).filter((name) => !(name in files));
  const changed = Object.keys(files).filter((name) => {
    const file = path.join(outDir, name);
    return !existsSync(file) || readFileSync(file, "utf8") !== files[name];
  });
  if (check) {
    for (const name of [...changed, ...stale]) warn(`sync-volunteers: data/positions/${name} differs from the kit`);
    if (changed.length + stale.length === 0) log("sync-volunteers: data/positions/ matches the kit");
    return changed.length + stale.length === 0 ? 0 : 1;
  }
  mkdirSync(outDir, { recursive: true });
  for (const name of changed) writeFileSync(path.join(outDir, name), files[name]);
  for (const name of stale) rmSync(path.join(outDir, name));
  log(`sync-volunteers: wrote ${changed.length}, removed ${stale.length}, unchanged ${Object.keys(files).length - changed.length}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main();
}
